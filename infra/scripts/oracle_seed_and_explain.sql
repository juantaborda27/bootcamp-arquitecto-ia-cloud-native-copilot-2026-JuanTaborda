-- 2. Creación de tablas de la aplicación
CREATE TABLE COURSES (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODE VARCHAR2(50) NOT NULL UNIQUE,
    TITLE VARCHAR2(150) NOT NULL
);

CREATE TABLE ENROLLMENTS (
    ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    STUDENT_ID VARCHAR2(50) NOT NULL,
    COURSE_ID VARCHAR2(50) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT UQ_STUDENT_COURSE UNIQUE (STUDENT_ID, COURSE_ID)
);

-- 3. Inserción masiva de 1.000 inscripciones sintéticas de prueba
INSERT INTO COURSES (CODE, TITLE) VALUES ('CRS-101', 'Arquitectura Cloud Native');
INSERT INTO COURSES (CODE, TITLE) VALUES ('CRS-102', 'Bases de Datos Enterprise');

BEGIN
    FOR i IN 1..1000 LOOP
        INSERT INTO ENROLLMENTS (STUDENT_ID, COURSE_ID, STATUS)
        VALUES ('STD-' || TRUNC(DBMS_RANDOM.VALUE(1, 100)), 'CRS-' || (101 + MOD(i, 2)), CASE WHEN MOD(i, 5) = 0 THEN 'PENDING' ELSE 'CONFIRMED' END);
    END LOOP;
    COMMIT;
END;
/

